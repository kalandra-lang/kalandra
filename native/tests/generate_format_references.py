"""Regenerate fixed-format reference vectors using Python's independent dtoa implementation."""
from pathlib import Path
import random
import struct

randomizer = random.Random(309)
rows = []
for width, kind in ((32, 'F32'), (64, 'F64')):
    edge_bits = ([0, 0x80000000, 1, 0x7f7fffff, 0x7f800000, 0xff800000, 0xffc12345]
                 if width == 32 else
                 [0, 0x8000000000000000, 1, 0x7fefffffffffffff,
                  0x7ff0000000000000, 0xfff0000000000000, 0xfff8000000000001])
    bits = edge_bits + [randomizer.getrandbits(width) for _ in range(48)]
    for index, raw in enumerate(bits):
        value = struct.unpack('>f' if width == 32 else '>d', raw.to_bytes(width//8, 'big'))[0]
        precision = [0, 2, 6, 17, 60][index % 5]
        rows.append((kind, raw, precision, format(value, f'.{precision}f')))
rows += [('F64', 1, 1074, format(struct.unpack('>d', (1).to_bytes(8, 'big'))[0], '.1074f')),
         ('F32', 0x3e000000, 1100, format(0.125, '.1100f'))]
lines = ['// Generated by generate_format_references.py; do not edit reference values.',
         '// clang-format off', 'inline constexpr FixedReference fixedReferences[] = {']
lines += [f'  {{K::{kind}, 0x{raw:x}ULL, {precision}, "{expected}"}},'
          for kind, raw, precision, expected in rows]
lines += ['};', '// clang-format on', '']
Path(__file__).with_name('FormatFixedReferences.h').write_text('\n'.join(lines), encoding='utf-8')
