"""Replay independently checked source fixtures under a selected Vulkan ICD.

ICD selection is external (VK_DRIVER_FILES); no CPU/software Vulkan substitute
is enabled here. Expected records are generated by the shared source test suite.
"""
import argparse
import json
import os
from pathlib import Path
import subprocess
p=argparse.ArgumentParser()
p.add_argument('root',type=Path)
a=p.parse_args()
records=sorted(a.root.glob('*/expected.json'))
assert records, 'No completed source fixtures with independent expected outputs'
for record in records:
    expected=json.loads(record.read_text())
    for workers in (1,2,4):
        result=subprocess.run([record.parent/'program'],text=True,capture_output=True,
            timeout=60,env=os.environ|{'KALANDRA_WORKERS':str(workers)})
        if expected['fault']:
            assert result.returncode!=0 and not result.stdout and f"Vulkan task failed: 1/{expected['fault']}" in result.stderr,(record,result)
        else:
            assert result.returncode==0 and result.stdout==expected['stdout'] and not result.stderr,(record,result)
    print('PASS:',record.parent.name,flush=True)
print('PASS:',len(records),'source fixtures at 1/2/4 workers',flush=True)
